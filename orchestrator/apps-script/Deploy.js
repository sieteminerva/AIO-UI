/**
 * DEPLOY — publish one generated site to GitHub Pages.
 *
 * The browser never sees the token: it sends the two emitted files and this file
 * commits them, enables Pages, and answers with the two URLs the result page shows.
 *
 * Script Properties:
 *   GITHUB_TOKEN  fine-grained PAT: Contents (write) + Pages (write); add
 *                 Administration (write) only when this file must create the repo
 *   GITHUB_OWNER  account that owns the site repos (default: the token's user)
 *   GITHUB_REPO   optional. A fixed repo for testing: every site lands in it and the
 *                 token can stay scoped to that one repo. Unset = one repo per site.
 *
 * Two modes, one code path: a fixed repo is "the repo name is a constant", otherwise
 * the preset id names the repo and a missing repo is created (needs Administration).
 */

/** One GitHub REST call; `path` starts with `/`. Throws the API message on failure. */
function github(method, path, body, allowNotFound) {
  const token = PROPS.getProperty("GITHUB_TOKEN");
  if (!token) throw new Error("Missing Script Property GITHUB_TOKEN.");

  const response = UrlFetchApp.fetch(`https://api.github.com${path}`, {
    method,
    contentType: "application/json",
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
    },
    ...(body ? { payload: JSON.stringify(body) } : {}),
    muteHttpExceptions: true,
  });

  const code = response.getResponseCode();
  if (allowNotFound && code === 404) return null;
  if (code < 200 || code >= 300) {
    throw new Error(`GitHub ${method} ${path} → HTTP ${code}: ${response.getContentText().slice(0, 300)}`);
  }
  return response.getContentText() ? JSON.parse(response.getContentText()) : null;
}

/** `Kriya Nusantara` / `kriya-nusantara` → `kriya-nusantara`. */
function repoName(value) {
  const clean = String(value || "")
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return clean || `aio-site-${Date.now()}`;
}

/**
 * Publishes `files` (usually `index.html` + `app.js`) as a Pages site.
 *
 * @param {{ name?: string, files?: Record<string, string> }} payload
 * @returns {{ repo: { title: string, url: string }, live: { title: string, url: string } }}
 */
function deploySite(payload) {
  const files = payload.files && typeof payload.files === "object" ? payload.files : {};
  const names = Object.keys(files);
  if (!names.length) throw new Error("`files` must name at least one file.");

  const token = PROPS.getProperty("GITHUB_TOKEN");
  if (!token) throw new Error("Missing Script Property GITHUB_TOKEN.");

  const owner = PROPS.getProperty("GITHUB_OWNER") || github("get", "/user").login;
  const fixed = PROPS.getProperty("GITHUB_REPO");
  const repo = fixed ? repoName(fixed) : repoName(payload.name);

  // Create only when the repo is not fixed: a fixed repo is created by the owner, and
  // the token that may not create repos is exactly the token this mode is built for.
  const existing = github("get", `/repos/${owner}/${repo}`, null, true);
  if (!existing && fixed) {
    throw new Error(`Repo ${owner}/${repo} tidak ada. Buat dulu, atau lepas GITHUB_REPO.`);
  }
  if (!existing) {
    github("post", "/user/repos", {
      name: repo,
      description: `Generated by Rajutan — ${payload.name || repo}`,
      private: false,
      auto_init: true,
    });
  }

  // The Contents API creates the branch on the first PUT; auto_init gives it a base.
  names.forEach((path) => {
    const current = github("get", `/repos/${owner}/${repo}/contents/${path}`, null, true);
    github("put", `/repos/${owner}/${repo}/contents/${path}`, {
      message: `rajutan: ${path}`,
      content: Utilities.base64Encode(String(files[path]), Utilities.Charset.UTF_8),
      ...(current && current.sha ? { sha: current.sha } : {}),
    });
  });

  // Pages: enable once, then report whatever GitHub already serves.
  let pages = github("get", `/repos/${owner}/${repo}/pages`, null, true);
  if (!pages) {
    pages = github("post", `/repos/${owner}/${repo}/pages`, {
      source: { branch: "main", path: "/" },
    });
  }

  const live = (pages && pages.html_url) || `https://${owner}.github.io/${repo}/`;
  return {
    repo: { title: `${owner}/${repo}`, url: `https://github.com/${owner}/${repo}` },
    live: { title: repo, url: live.replace(/\/?$/, "/") },
  };
}
