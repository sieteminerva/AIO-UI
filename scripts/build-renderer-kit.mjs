#!/usr/bin/env node
/**
 * RENDERER KIT — `DOMRenderer` as a file that needs nobody.
 *
 * External projects migrate by copying one file. That only works if the file has **zero**
 * `@aio-ui/*` imports, so this script assembles it from the real sources instead of keeping
 * a hand-copied fork that silently drifts:
 *
 *   packages/core/src/DOMRenderer/index.ts   the class
 *   packages/utilities/src/Metadata.ts       `ensureMetadataIdentity`, `setMetadata`
 *   packages/utilities/src/AttributeUtils.ts `applyAttrDictionary`, `applyAttributeList`
 *
 * and replaces the two core-internal seams:
 *
 *   getTemplates()            -> a local `Map`-based store (same register/unregister shape)
 *   import.meta.env?.DEV      -> `KIT_DEV`, false: a published kit has no dev console budget
 *
 * Output: `packages/dom-renderer/src/DOMRenderer.ts` (committed, generated).
 *
 * Usage:
 *   node scripts/build-renderer-kit.mjs           # write the kit
 *   node scripts/build-renderer-kit.mjs --check   # exit 1 when the kit is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const checks = process.argv.slice(2).includes("--check");

const CORE = join(ROOT, "packages", "core", "src", "DOMRenderer", "index.ts");
const ATTR = join(ROOT, "packages", "utilities", "src", "AttributeUtils.ts");
const META = join(ROOT, "packages", "utilities", "src", "Metadata.ts");
const OUT = join(ROOT, "packages", "modules", "dom-renderer", "src", "DOMRenderer.ts");

/** Drops import statements (and optionally the `export` keyword), keeping every declaration. */
function body(file, { keepExport = false } = {}) {
  const text = readFileSync(file, "utf8").replace(/^import[\s\S]*?;\s*$/gm, "");
  return (keepExport ? text : text.replace(/^export\s+(?=(?:function|class|const|let|interface|type)\b)/gm, "")).trim();
}

const PREAMBLE = `/**
 * GENERATED by \`scripts/build-renderer-kit.mjs\` — do not edit by hand.
 *
 * A copy of \`@aio-ui/core\`'s \`DOMRenderer\` with its two internal seams inlined, so this
 * file imports nothing. Run \`node scripts/build-renderer-kit.mjs --check\` when the renderer
 * changes; the differential test proves this copy and the original build the same DOM.
 */

/** A builder name. The kit has no registry type, so any string is a candidate. */
export type BuilderName = string;

/** Layout selector names a page may use. */
export type DefaultSelectors = "grid" | "row" | "column" | string;

export interface iMetadataContext {
  scopeId: string;
  parentKey: string | null;
}

export interface iNodeRecordRelations {
  scope?: string;
  key?: string;
  template?: string;
  parent?: string | null;
  children?: string[];
  elements?: string[];
}

export interface iNodeRecordItem<T = any> {
  key: string;
  element: HTMLElement;
  payload: T;
  relations?: iNodeRecordRelations;
}

/** The declarative tree the renderer walks. */
export type iNodeContent<S extends string = DefaultSelectors> = Record<string | S, any>;

declare global {
  interface HTMLSelectElement {
    __nativeChangeHandler: (e: Event) => any;
  }
  interface HTMLElement {
    __outer: HTMLElement;
    __inner: HTMLElement;
    __payload: any;
    __index: number;
    __templateId: string;
    getMetadata: ((context?: iMetadataContext) => any) | undefined | null;
    mount: (compositeOutput: any) => void;
  }
}

/** The kit is a published artefact: development-only warnings stay off. */
const KIT_DEV = false;

/** Template overrides, keyed \`themeId:selectorKey\` — the same shape \`TemplateRegistry\` offers. */
const templates = new Map<string, (typeKey: string, element: HTMLElement, payload: any, selector: any) => void | Promise<void>>();
const getTemplates = () => ({
  register: (themeId: string, key: string, handler: (typeKey: string, element: HTMLElement, payload: any, selector: any) => void | Promise<void>) =>
    templates.set(\`\${themeId}:\${key}\`, handler),
  unregister: (themeId: string, key: string) => templates.delete(\`\${themeId}:\${key}\`),
});

`;

const renderer = body(CORE, { keepExport: true })
  .replace(/keyof iBuilderRegistry/g, "BuilderName")
  .replace(/import\.meta\.env\?\.DEV/g, "KIT_DEV");

if (/from\s+["']@aio-ui\//.test(renderer)) {
  console.error("build-renderer-kit: the renderer still imports a workspace package — fix the kit's preamble first");
  process.exit(1);
}

const kit = `${PREAMBLE}// ---- inlined from @aio-ui/utilities.ts -----------------------------
${body(META)}
export { buildNamespace };

// ---- inlined from @aio-ui/utilities.ts -----------------------
${body(ATTR)}

// ---- the renderer ----------------------------------------------------------
${renderer}
`;

const target = relative(ROOT, OUT).replace(/\\/g, "/");
if (checks) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    current = "";
  }
  if (current !== kit) {
    console.error(`✖ ${target} is stale — run node scripts/build-renderer-kit.mjs`);
    process.exit(1);
  }
  console.log(`✓ renderer kit up to date (${(kit.length / 1024).toFixed(1)} kB)`);
} else {
  writeFileSync(OUT, kit);
  console.log(`renderer kit written: ${target} (${(kit.length / 1024).toFixed(1)} kB)`);
}
